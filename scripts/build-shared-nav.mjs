#!/usr/bin/env node
// Builds the navigation used by the static pages (public/*.html) from the real React homepage nav,
// so every page shows exactly the same nav. Runs after `vite build` + prerender (see package.json).
// Source of truth: src/components/Nav.tsx, rendered into dist/index.html, and its compiled CSS.
// Outputs dist/assets/shared-nav.{css,js} and keeps public/assets/ copies in sync.
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const root=join(dirname(fileURLToPath(import.meta.url)),'..');
const home=readFileSync(join(root,'dist/index.html'),'utf8');
const markup=home.match(/<header class="nav[^"]*">[\s\S]*?<\/header>\s*<div class="nav-overlay[^"]*">[\s\S]*?<\/div>/);
if(!markup)throw new Error('build-shared-nav: prerendered nav not found in dist/index.html');
const html=markup[0].replace(/class="nav "/,'class="nav"').replace(/class="nav-burger "/,'class="nav-burger"').replace(/class="nav-overlay "/,'class="nav-overlay"');
const cssFile=[...home.matchAll(/<link rel="stylesheet"[^>]*href="(\/assets\/[^"]+\.css)"/g)].map(m=>m[1])[0];
if(!cssFile)throw new Error('build-shared-nav: homepage stylesheet not found');
const css=readFileSync(join(root,'dist',cssFile),'utf8');

// Minimal CSS parser (comments, strings, nested @media/@supports).
function parse(src){
 src=src.replace(/\/\*[\s\S]*?\*\//g,'');let i=0;
 const scan=()=>{let q=null;while(i<src.length){const c=src[i];if(q){if(c==='\\')i++;else if(c===q)q=null}else if(c==='"'||c==="'")q=c;else if(c==='{'||c===';'||c==='}')break;i++}};
 function block(){
  const out=[];
  while(i<src.length){
   const start=i;scan();const head=src.slice(start,i).trim();
   if(i>=src.length)break;
   if(src[i]==='}'){i++;return out}
   if(src[i]===';'){i++;continue}
   i++;
   if(/^@(media|supports|layer)/.test(head)){out.push({group:head,children:block()});continue}
   let d=1,q=null;const b=i;
   while(i<src.length&&d){const c=src[i];if(q){if(c==='\\')i++;else if(c===q)q=null}else if(c==='"'||c==="'")q=c;else if(c==='{')d++;else if(c==='}')d--;i++}
   out.push({head,body:src.slice(b,i-1)});
  }
  return out;
 }
 return block();
}
const split=s=>{const o=[];let d=0,c='';for(const ch of s){if(ch==='('||ch==='[')d++;if(ch===')'||ch===']')d--;if(ch===','&&!d){o.push(c);c=''}else c+=ch}o.push(c);return o.map(x=>x.trim()).filter(Boolean)};
const NAV=/\.(nav|nav-[\w-]+|wordmark|brand-logo)(?![\w-])/;
const tree=parse(css),used=new Set(['--font-body','--font-display']);
function pick(nodes){
 const out=[];
 for(const n of nodes){
  if(n.group){if(/^@(keyframes|font-face)/.test(n.group))continue;const k=pick(n.children);if(k.length)out.push(n.group+'{'+k.join('')+'}');continue}
  if(n.head.startsWith('@'))continue;
  const sel=split(n.head).filter(s=>NAV.test(s));
  if(!sel.length)continue;
  for(const m of n.body.matchAll(/var\(\s*(--[\w-]+)/g))used.add(m[1]);
  out.push(sel.join(',')+'{'+n.body+'}');
 }
 return out;
}
const rules=pick(tree);
const flat=n=>n.group?n.children.flatMap(flat):[n];
const roots=tree.flatMap(flat).filter(n=>n.head&&split(n.head).some(s=>s===':root'||s==='html'));
for(let k=0;k<4;k++)for(const n of roots)for(const d of n.body.split(';')){const [name,...v]=d.split(':');if(used.has(name.trim()))for(const m of v.join(':').matchAll(/var\(\s*(--[\w-]+)/g))used.add(m[1])}
function vars(nodes){
 const out=[];
 for(const n of nodes){
  if(n.group){if(n.group.startsWith('@media')||n.group.startsWith('@supports')){const k=vars(n.children);if(k.length)out.push(n.group+'{'+k.join('')+'}')}continue}
  if(!n.head||!split(n.head).some(s=>s===':root'||s==='html'))continue;
  const decl=n.body.split(';').map(d=>d.trim()).filter(d=>used.has(d.split(':')[0].trim()));
  if(decl.length)out.push('.nav,.nav-overlay{'+decl.join(';')+'}');
 }
 return out;
}
// Base text the homepage nav inherits from <body>, pinned so a page's own styles cannot leak in.
const base='.nav,.nav-overlay{font-family:var(--font-body);font-size:16px;line-height:normal;letter-spacing:normal;font-weight:400;color:#f2f0eb;-webkit-font-smoothing:antialiased;box-sizing:border-box}.nav-burger{color:#fff;font-size:13.3333px;font-family:var(--font-body);padding:1px 6px;border:0;border-radius:0;margin:0;min-width:0;min-height:0;box-shadow:none;text-transform:none;letter-spacing:normal;line-height:normal}.nav *,.nav-overlay *{box-sizing:border-box}.nav a,.nav-overlay a{text-decoration:none}.nav img{max-width:none}';
const outCss='/* Generated by scripts/build-shared-nav.mjs from the homepage nav. Do not edit by hand. */\n'+vars(tree).join('\n')+'\n'+base+'\n'+rules.join('\n')+'\n';

const outJs='/* Generated by scripts/build-shared-nav.mjs from the homepage nav (src/components/Nav.tsx). Do not edit by hand. */\n'+
"(function(){if(document.querySelector('header.nav'))return;var t=document.createElement('template');t.innerHTML="+JSON.stringify(html)+";"+
"var header=t.content.querySelector('header'),overlay=t.content.querySelector('.nav-overlay');document.body.insertBefore(t.content,document.body.firstChild);document.body.classList.add('axis-shared-page');"+
"var burger=header.querySelector('.nav-burger');function setOpen(o){burger.classList.toggle('open',o);overlay.classList.toggle('open',o);burger.setAttribute('aria-expanded',String(o));document.body.style.overflow=o?'hidden':''}"+
"burger.setAttribute('aria-expanded','false');burger.addEventListener('click',function(){setOpen(!overlay.classList.contains('open'))});"+
"header.querySelectorAll('a').forEach(function(a){a.addEventListener('click',function(){setOpen(false)})});overlay.querySelectorAll('a').forEach(function(a){a.addEventListener('click',function(){setOpen(false)})});"+
"document.addEventListener('keydown',function(e){if(e.key==='Escape'&&overlay.classList.contains('open')){setOpen(false);burger.focus()}});"+
"function onScroll(){header.classList.toggle('scrolled',window.scrollY>20)}onScroll();window.addEventListener('scroll',onScroll,{passive:true})})();\n";

for(const dir of ['dist/assets','public/assets']){mkdirSync(join(root,dir),{recursive:true});writeFileSync(join(root,dir,'shared-nav.css'),outCss);writeFileSync(join(root,dir,'shared-nav.js'),outJs)}
console.log('shared nav: '+rules.length+' rules from '+cssFile);
